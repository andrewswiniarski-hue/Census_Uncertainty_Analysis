def _rules_text() -> str:
    names = ["esri", "nchs"] + (["hud"] if HUD_RULE_VERIFIED else [])
    return "\n".join(f"- [[rule.{n}]]: {RULES[n]}" for n in names)


def _glossary_text() -> str:
    return "\n".join(f"- {k}: {v}" for k, v in GLOSSARY.items())


