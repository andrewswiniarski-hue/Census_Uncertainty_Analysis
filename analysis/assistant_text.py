"""All wording for the dashboard's "Ask about this county" assistant.

What it does: holds every piece of text the assistant uses, so the lead can
edit wording without touching logic: the standing instructions sent to the
model (SYSTEM_PROMPT), the three ready-made prompts and their button labels
(PRESETS), the fixed texts shown in place of a model answer, the glossary of
terms the model may explain, the outside-rule sentences, and the phrase lists
the checks in analysis/assistant.py use.

What it needs: nothing. No imports beyond the standard library.

What it produces: plain strings, tuples and dictionaries. analysis/assistant.py
and Streamlit/us_county_explorer.py import them.

Spec: docs/design-specs/2026-10-10-county-ai-assistant-design.md
("The three ready-made prompts" and "Fixed texts" are copied word for word).
Rules for this file: no em dashes; "U.S. Census Bureau" on first mention and
"Census Bureau" after, never "the Bureau"; band names exactly as on the cards.
"""

